SELECT '=========================================' AS '';
SELECT '  SPC 统计分析 DEMO 数据验证' AS '';
SELECT '=========================================' AS '';

SELECT '--- 控制图统计 ---' AS section;
SELECT
    COUNT(*) AS '控制图总数',
    SUM(CASE WHEN chart_type = 'Xbar_R' THEN 1 ELSE 0 END) AS 'Xbar-R',
    SUM(CASE WHEN chart_type = 'Xbar_S' THEN 1 ELSE 0 END) AS 'Xbar-S',
    SUM(CASE WHEN chart_type = 'I_MR' THEN 1 ELSE 0 END) AS 'I-MR',
    SUM(CASE WHEN chart_type = 'P' THEN 1 ELSE 0 END) AS 'P图',
    SUM(CASE WHEN chart_type = 'C' THEN 1 ELSE 0 END) AS 'C图',
    SUM(CASE WHEN chart_type = 'U' THEN 1 ELSE 0 END) AS 'U图'
FROM spc_control_charts;

SELECT '--- 数据点统计 ---' AS section;
SELECT
    ChartId,
    (SELECT name FROM spc_control_charts c WHERE c.id = d.ChartId) AS '控制图名称',
    (SELECT chart_type FROM spc_control_charts c WHERE c.id = d.ChartId) AS '类型',
    COUNT(*) AS '数据点数'
FROM spc_data_points d
GROUP BY ChartId
ORDER BY ChartId;

SELECT '--- 分析结果统计 ---' AS section;
SELECT
    COUNT(*) AS '分析记录总数',
    SUM(CASE WHEN AnalysisType = 'cpk' THEN 1 ELSE 0 END) AS 'CPK分析',
    SUM(CASE WHEN AnalysisType = 'capability' THEN 1 ELSE 0 END) AS '能力分析'
FROM spc_analysis_results;

SELECT '--- 判异规则统计 ---' AS section;
SELECT
    COUNT(*) AS '规则总数',
    SUM(Enabled) AS '启用中',
    SUM(!Enabled) AS '已禁用'
FROM spc_alert_rules;

SELECT '--- 触发记录统计 ---' AS section;
SELECT
    COUNT(*) AS '触发总数',
    SUM(Resolved) AS '已解决',
    SUM(!Resolved) AS '未解决'
FROM spc_alert_triggers;

SELECT '--- ANOVA 分析统计 ---' AS section;
SELECT
    COUNT(*) AS '分析记录总数',
    SUM(Significant) AS '显著因素',
    SUM(!Significant) AS '不显著因素'
FROM spc_anova_results;

SELECT '--- 数据源统计 ---' AS section;
SELECT
    source_type AS '数据源类型',
    COUNT(*) AS '数量'
FROM spc_data_sources
GROUP BY source_type;

SELECT '--- 各控制图 CPK 对比 ---' AS section;
SELECT
    c.name AS '控制图',
    c.chart_type AS '类型',
    a.AnalysisType AS '分析类型',
    a.Cpk AS 'Cpk',
    a.Pp AS 'Pp',
    a.EstimatedPpm AS '估计PPM'
FROM spc_analysis_results a
JOIN spc_control_charts c ON c.id = a.ChartId
WHERE a.AnalysisType = 'cpk'
ORDER BY a.Cpk DESC;
